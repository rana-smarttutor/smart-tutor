export function getSchoolBoardSyllabus(
  grade: number,
  board: SchoolBoard,
  stream: JuniorStream = "science",
): SyllabusSubject[] {
  if (grade >= 6 && grade <= 10) {
    return school[grade]?.[board] ?? [];
  }

  if (grade === 11 || grade === 12) {
    return senior[grade][board][stream];
  }

  return [];
}
